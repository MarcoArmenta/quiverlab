"""tau-exceptional sequences (Buan-Marsh) via the Jasso tau-perpendicular reduction
(Plan 65 / R27; Buan-Marsh J. Algebra 585 (2021); Jasso IMRN 2015; Demonet-Iyama-Jasso 2019).

Over a **tau-tilting-finite** ``A = kQ/I`` the *signed* tau-exceptional sequences are built on
the shipped P45 tau-tilting engine:

- a length-1 **signed tau-exceptional object** is either an indecomposable **tau-rigid**
  module ``(M, +)`` or a **shifted projective** ``(P_v[1], -)`` (one per vertex);
- a complete signed tau-exceptional sequence ``(M_1, ..., M_n)`` has, at one end, a signed
  object ``M`` of ``A``, and the remaining ``n-1`` terms form a complete signed
  tau-exceptional sequence of the **reduction algebra** ``C(M)`` -- the Jasso
  tau-perpendicular category ``J(M) ~ mod C(M)``, of rank ``n - |M|``.

The reduction dispatches on the SIGN of the outer object (H2):

- **tau-rigid module ``U``** -> the DIJ idempotent quotient ``C(U) = End(T_U)/<e_U>``
  (``T_U`` a genuine tau-tilting module -- an empty-support exchange-graph vertex -- with
  ``U in add T_U``). We build ``End(T_U)`` in the ``hom_basis`` and quotient by the
  two-sided ideal generated by the summand projector ``e_U`` **at the structure-constant
  level**, THEN present the quotient (``presented_form``). This sidesteps a fragile
  vertex-identification in the presented ``End(T_U)`` (H5): the quotient is intrinsic and
  ``C(S_1) of kA_3`` comes out ``kA_2`` (connected, dim 3), not ``k x k`` (dim 2).
- **shifted projective ``P_v[1]``** -> the support quotient ``C(P_v[1]) = A/<e_v>`` (delete
  vertex ``v``), with ``F`` the tautological restriction ``mod(A/<e_v>) ~ {M in mod A : M_v
  = 0}`` (``Recollement.i_upper_star``).

**Enumeration** is the Buan-Marsh **ordered-support-tau-tilt bijection**:
``#(complete signed tau-exceptional sequences) = n! * #(support tau-tilting pairs)``, with
``#sTt = len(exchange_graph(A).vertices)`` from P45. It is NOT a mutation-BFS (mutation
transitivity is proven only in rank 2, Buan-Hanson-Marsh arXiv:2402.10301). The formula
identity ``signed_count == n! * #sTt`` is a SELF-CERT (tautological); the genuine
cross-check is the **materialisation** of the reduction towers (``want_sequences=True``):
their number equals ``signed_count``, they are pairwise distinct, and each is recognized.

**Honest gates (M1):** the count is trustworthy only from a ``status="complete"`` exchange
graph; ``status in {"budget","error"}`` -> a loud refusal report, never a count off a
non-complete graph. tau-tilting-infinite -> refusal. Char ``<= dim`` over ``GF(p)`` -> the
shipped decompose/is_isomorphic/presented_form caveat raises loudly.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from math import factorial

from quiverlab.errors import QuiverlabError


# --------------------------------------------------------------------------- #
# signed tau-exceptional objects
# --------------------------------------------------------------------------- #
@dataclass
class TauExcObject:
    """A length-1 signed tau-exceptional object: ``sign = +1`` for an indecomposable
    tau-rigid module (``module``), ``sign = -1`` for a shifted projective ``P_vertex[1]``
    (``module = None``, ``vertex`` set)."""
    sign: int
    module: object = None
    vertex: object = None

    def dvt(self):
        """A hashable signature: (sign, dim-vector-tuple) for a module; (sign, ('P', vertex))
        for a shifted projective."""
        if self.sign < 0:
            return (-1, ("P", self.vertex))
        dv = self.module.dimension_vector()
        return (1, tuple(dv[w] for w in sorted(dv)))

    def __repr__(self):
        if self.sign < 0:
            return f"P_{self.vertex}[1]"
        dv = self.module.dimension_vector()
        return "(" + ",".join(str(dv[w]) for w in sorted(dv)) + ")"


@dataclass
class TauReduction:
    """The Jasso tau-perpendicular reduction ``C(U)`` of a signed object ``U`` (Plan 65 /
    R27). ``reduction_algebra`` is a genuine ``kQ'/I'`` Algebra of rank ``n - |U|``;
    ``kind`` is ``"tau_rigid"`` (DIJ ``End(T_U)/<e_U>``) or ``"shifted"`` (``A/<e_v>``);
    ``bongartz`` is the tau-tilting completion ``T_U`` (the pair, tau-rigid case) or ``None``;
    ``u_vertices`` records the killed summand indices / the deleted vertex; ``equivalence``
    is the object-transport ``mod C(U) -> J(U) inverse`` (a callable, shifted case only --
    the cheap restriction; ``None`` for the tau-rigid case, whose deep lift is scope-bounded
    -- see the module docstring)."""
    reduction_algebra: object
    bongartz: object = None
    u_vertices: object = None
    kind: str = "tau_rigid"
    equivalence: object = None


@dataclass
class TauExcReport:
    """The signed tau-exceptional-sequence report of a tau-tilting-finite algebra
    (Plan 65 / R27)."""
    algebra: object
    n: int
    signed_count: int = 0            # = n! * #sTt  (the bijection count; 0 iff not complete)
    stt_count: int = 0               # #support tau-tilting pairs (P45); 0 iff not complete
    sequences: list | None = None    # reduction towers (None if want_sequences=False/capped)
    is_complete: bool = False        # False iff tau-tilting-infinite / non-complete graph
    status: str = "unsupported"      # "complete" | "budget" | "unsupported" | "error"
    note: str = ""


@dataclass
class _TowerEntry:
    """One rung of a materialised reduction tower: a signed object ``obj`` living over the
    algebra ``algebra`` (of rank ``rank``). A complete signed tau-exceptional sequence is
    the tower ``[(A, M_n), (C(M_n), M_{n-1}), ..., (rank-1 algebra, M_1)]``. ``index`` is the
    object's position in its level's enumeration -- it disambiguates NON-isomorphic objects
    with a coinciding dim-vector (e.g. ``P_1``/``P_2`` of ``k(1<->2)/rad^2``, both dim-vector
    ``(1,1)``), which ``dvt`` alone cannot."""
    algebra: object
    obj: TauExcObject
    rank: int
    index: int = -1

    def key(self):
        """A per-rung dedup signature ``(rank, index, obj.dvt())``. Along a tower the tuple
        of rung keys is a UNIQUE path key: a shared prefix => the same reduction algebra =>
        the same enumeration => distinct objects have distinct ``index``."""
        return (self.rank, self.index, self.obj.dvt())


def _require_quiver(A, what):
    if getattr(A, "quiver", None) is None:
        raise QuiverlabError(
            f"{what}: requires a quiver-presented algebra kQ/I (a structure-constant-only "
            "algebra has no vertices to reduce)")


def _rank(A):
    return len(list(A.quiver.vertices))


def _provably_tau_tilting_infinite(A):
    """A CHEAP sufficient certificate of tau-tilting-INfiniteness (never a false positive):
    a **hereditary** connected **non-Dynkin** ``kQ`` is representation-infinite (Gabriel),
    hence tau-tilting-infinite -- refuse instantly, never build the (infinite) exchange
    graph (the 2-Kronecker walk is unbounded). Returns ``False`` (unknown) for every other
    algebra, deferring to the honest exchange-graph budget cap."""
    if getattr(A, "quiver", None) is None:
        return False
    from quiverlab.invariants.dynkin_type import dynkin_type, is_connected
    from quiverlab.invariants.recognizers import is_hereditary
    if is_hereditary(A) and is_connected(A.quiver):
        dt = dynkin_type(A.quiver)
        return not (dt and dt[0] in ("A", "D", "E"))
    return False


