# Task A2: the recognizer
# --------------------------------------------------------------------------- #
def _is_signed_object(A, obj):
    """True iff ``obj`` (a :class:`TauExcObject`, over algebra ``A``) is a genuine length-1
    signed tau-exceptional object of ``A``."""
    from quiverlab.modules.decompose import is_indecomposable
    from quiverlab.tautilting.rigid import is_tau_rigid
    if not isinstance(obj, TauExcObject):
        return False
    if obj.sign < 0:
        return obj.vertex in set(A.quiver.vertices)
    M = obj.module
    if M is None or getattr(M, "algebra", None) is not A:
        return False
    return is_tau_rigid(M) and is_indecomposable(M)


def _entry_module(x):
    """The genuine module of an ambient sequence entry (a :class:`Module` or a positive
    :class:`TauExcObject`), else ``None`` (a shifted object)."""
    if isinstance(x, TauExcObject):
        return x.module if x.sign > 0 else None
    return x


def _entry_shift_vertex(x):
    """The shifted-projective vertex of an ambient sequence entry, else ``None``."""
    if isinstance(x, TauExcObject) and x.sign < 0:
        return x.vertex
    return None


def _verify_tower(A, seq):
    """A materialised tower ``[(A, M_n), (C_1, M_{n-1}), ...]`` is genuine iff every rung's
    object is a signed tau-exceptional object of its algebra, the ranks descend
    ``n, n-1, ..., 1``, and the length is ``n = rk A``."""
    n = _rank(A)
    if len(seq) != n:
        return False
    if seq and seq[0].algebra is not A:
        return False
    for i, entry in enumerate(seq):
        if entry.rank != n - i:
            return False
        if _rank(entry.algebra) != n - i:
            return False
        if not _is_signed_object(entry.algebra, entry.obj):
            return False
    return True


def is_tau_exceptional_sequence(A, seq):
    """True iff ``seq`` is a complete-or-partial signed tau-exceptional sequence of ``A``
    (Plan 65 / R27; the ``(inner, ..., outer)`` convention -- the outer term is the
    reduced-away end ``seq[-1]``).

    Two input forms are accepted:

    - a **reduction tower** (a list of :class:`_TowerEntry`, as produced by
      :func:`tau_exceptional_sequences`): verified rung-by-rung;
    - an **ambient sequence** (a list of :class:`Module` / :class:`TauExcObject`): recognized
      recursively -- the outer signed object reduces, the remaining terms are transported
      into ``C(outer)`` and recognized there. Over a hereditary ``A`` an all-module sequence
      is recognized by the classical criterion (the Buan-Marsh coincidence, tau-exc =
      classical exc for hereditary)."""
    _require_quiver(A, "is_tau_exceptional_sequence")
    seq = list(seq)
    if not seq:
        return True
    if all(isinstance(e, _TowerEntry) for e in seq):
        return _verify_tower(A, seq)
    return _recognize_ambient(A, seq)


def _recognize_ambient(A, seq):
    from quiverlab.invariants.recognizers import is_hereditary
    # hereditary + all-module: tau-exceptional == classical exceptional (Buan-Marsh)
    mods = [_entry_module(x) for x in seq]
    if all(m is not None for m in mods) and is_hereditary(A):
        from quiverlab.modules.exceptional import is_exceptional_sequence
        return is_exceptional_sequence(A, mods)
    # general: validate the outer object, reduce, transport the inner terms, recurse
    outer = seq[-1]
    if not _as_signed_and_valid(A, outer):
        return False
    if len(seq) == 1:
        return True
    v = _entry_shift_vertex(outer)
    if v is None:
        # tau-rigid outer over a non-hereditary / mixed ambient sequence: the deep
        # object-lift F^{-1} is scope-bounded (honest -- see the module docstring). The
        # hereditary all-module case is handled above; the count oracle carries completeness.
        raise QuiverlabError(
            "is_tau_exceptional_sequence: an ambient sequence with a tau-rigid OUTER term "
            "over a non-hereditary algebra needs the deep tau-perpendicular object-lift "
            "F^{-1}, which is scope-bounded (Plan 65 honest scope); pass the reduction "
            "tower form, or use the count oracle (n! * #sTt)")
    red = tau_perpendicular_reduction(A, _as_shift_object(A, outer))
    C, transport = red.reduction_algebra, red.equivalence
    inner = []
    for x in seq[:-1]:
        m = _entry_module(x)
        if m is None:
            inner.append(x)                             # a shifted inner stays shifted
            continue
        if m.dimension_vector().get(v, 0) != 0:
            return False                                # not supported off v: not in J(P_v[1])
        inner.append(transport(m))
    return is_tau_exceptional_sequence(C, inner)


def _as_signed_and_valid(A, x):
    """True iff the ambient entry ``x`` is a genuine length-1 signed tau-exceptional object
    of ``A`` (a tau-rigid indecomposable module, or a shifted projective)."""
    from quiverlab.modules.decompose import is_indecomposable
    from quiverlab.tautilting.rigid import is_tau_rigid
    v = _entry_shift_vertex(x)
    if v is not None:
        return v in set(A.quiver.vertices)
    m = _entry_module(x)
    if m is None or getattr(m, "algebra", None) is not A:
        return False
    return is_tau_rigid(m) and is_indecomposable(m)


def _as_shift_object(A, x):
    """Coerce an ambient shifted entry to a negative :class:`TauExcObject` for the reduction
    sign-dispatch."""
    if isinstance(x, TauExcObject):
        return x
    return TauExcObject(-1, vertex=_entry_shift_vertex(x))


# --------------------------------------------------------------------------- #
# Task A3: enumeration via the ordered-sTt bijection + materialisation
# --------------------------------------------------------------------------- #
def _enumerate_towers(A, eg):
    """The materialised complete signed tau-exceptional sequences of ``A`` as reduction
    towers (Task A3 -- the H1 cross-check). Realises the Buan-Marsh recursion: pick an outer
    signed object ``M``, then a complete tower of ``C(M)``. ``eg`` is the (complete)
    exchange graph of ``A``."""
    n = _rank(A)
    objs = _objects_from_eg(A, eg)
    towers = []
    for i, M in enumerate(objs):
        entry = _TowerEntry(A, M, n, i)
        if n == 1:
            towers.append([entry])
            continue
        C = tau_perpendicular_reduction(A, M, _eg=eg).reduction_algebra
        from quiverlab.tautilting.mutation import exchange_graph
        egC = exchange_graph(C, budget_pairs=max(512, len(eg.vertices)))
        if egC.status != "complete":
            raise QuiverlabError(
                "tau_exceptional_sequences: a reduction algebra C(U) was not "
                f"tau-tilting-finite (status={egC.status!r}) -- unexpected (report it)")
        for sub in _enumerate_towers(C, egC):
            towers.append([entry] + sub)
    return towers


def tau_exceptional_sequences(A, *, budget=4096, want_sequences=True):
    """The complete signed tau-exceptional sequences of a **tau-tilting-finite** ``A``
    (Plan 65 / R27). The count is the ordered-support-tau-tilt bijection
    ``signed_count = n! * #sTt`` with ``#sTt = len(exchange_graph(A).vertices)`` -- computed
    WITHOUT enumerating, so it is exact even when materialisation is budget-capped.

    ``want_sequences=True`` also MATERIALISES the reduction towers (the H1 cross-check:
    ``len(sequences) == signed_count``, pairwise distinct, each recognized), capped at
    ``budget`` towers (``signed_count`` stays exact via the formula). Returns a
    :class:`TauExcReport`.

    Gate (M1): only a ``status="complete"`` exchange graph yields a count; ``status in
    {"budget","error"}`` -> an honest refusal report, NEVER a count off a non-complete graph."""
    _require_quiver(A, "tau_exceptional_sequences")
    from quiverlab.tautilting.mutation import exchange_graph
    n = _rank(A)
    if _provably_tau_tilting_infinite(A):
        return TauExcReport(
            A, n, 0, 0, None, False, "budget",
            "hereditary connected non-Dynkin => representation-infinite (Gabriel) => "
            "tau-tilting-infinite; the signed tau-exceptional count is infinite (no count "
            "derived)")
    eg = exchange_graph(A, budget_pairs=max(budget, 512))
    if eg.status != "complete":
        note = ("the exchange graph is not complete "
                f"(status={eg.status!r}); tau-tilting-infinite or a P45 mutation failure -- "
                "no signed tau-exceptional count is derived from a non-complete graph (M1)")
        status = eg.status if eg.status in ("budget", "error") else "unsupported"
        return TauExcReport(A, n, 0, 0, None, False, status, note)
    stt = len(eg.vertices)
    signed = factorial(n) * stt
    if not want_sequences:
        return TauExcReport(A, n, signed, stt, None, True, "complete", "")
    if signed > budget:
        return TauExcReport(
            A, n, signed, stt, None, True, "complete",
            f"materialisation capped: signed_count={signed} > budget={budget}; the count is "
            "exact via the bijection formula, sequences not materialised")
    towers = _enumerate_towers(A, eg)
    note = ""
    if len(towers) != signed:                           # a genuine reduction bug -> loud note
        note = (f"materialised {len(towers)} towers != signed_count {signed} -- a bug in the "
                "tau-perpendicular reduction or object enumeration (report it)")
    return TauExcReport(A, n, signed, stt, towers, True, "complete", note)


