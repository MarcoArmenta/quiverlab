# the length-1 signed objects
# --------------------------------------------------------------------------- #
def _indec_tau_rigids_from_eg(eg):
    """The indecomposable tau-rigid modules = the union of the exchange-graph pairs'
    summands, deduped by ``is_isomorphic`` within a dim-vector bucket (a distinct object
    with a coinciding dim-vector is kept -- the object count must be exact for the
    materialisation cross-check)."""
    from quiverlab.modules.hom import is_isomorphic
    seen = []                                            # (dvt, module)
    indecs = []
    for rec in eg.vertices:
        for M in rec["pair"].summands:
            dv = M.dimension_vector()
            key = tuple(dv[w] for w in sorted(dv))
            if any(k == key and is_isomorphic(m, M) for k, m in seen):
                continue
            seen.append((key, M))
            indecs.append(M)
    return indecs


def _objects_from_eg(A, eg):
    """The length-1 signed tau-exceptional objects from a complete exchange graph: every
    indecomposable tau-rigid module (sign +1) plus one shifted projective ``P_v[1]`` per
    vertex (sign -1)."""
    objs = [TauExcObject(1, module=M) for M in _indec_tau_rigids_from_eg(eg)]
    for v in A.quiver.vertices:
        objs.append(TauExcObject(-1, vertex=v))
    return objs


def tau_exceptional_objects(A, *, budget=512):
    """The length-1 signed tau-exceptional objects of ``A`` (Plan 65 / R27): every
    indecomposable **tau-rigid** module (sign ``+1``, from the exchange-graph module
    universe) plus one **shifted projective** ``P_v[1]`` per vertex (sign ``-1``). Requires a
    tau-tilting-finite ``A`` for the module part (loud refusal otherwise)."""
    _require_quiver(A, "tau_exceptional_objects")
    if _provably_tau_tilting_infinite(A):
        raise QuiverlabError(
            "tau_exceptional_objects: a hereditary connected non-Dynkin algebra is "
            "representation-infinite (Gabriel), hence tau-tilting-infinite; the tau-rigid "
            "module universe is infinite")
    from quiverlab.tautilting.mutation import exchange_graph
    eg = exchange_graph(A, budget_pairs=budget)
    if eg.status != "complete":
        raise QuiverlabError(
            "tau_exceptional_objects: the exchange graph is not complete "
            f"(status={eg.status!r}); the tau-rigid module universe is unavailable "
            "(tau-tilting-infinite or a P45 mutation failure)")
    return _objects_from_eg(A, eg)


# --------------------------------------------------------------------------- #
# Task A1: the Jasso tau-perpendicular reduction C(U)
# --------------------------------------------------------------------------- #
def _quotient_by_idempotent_sc(B0, e):
    """The quotient ``B0 / <e>`` of a structure-constant algebra by the two-sided ideal
    generated by the idempotent (coordinate vector) ``e``, returned as a NEW
    structure-constant :class:`Algebra`. ``<e> = B0 . e . B0`` (``B0`` has 1); the quotient
    basis is a complement of ``<e>``, structure constants induced by projection along
    ``<e>``. Exact, no floats."""
    from quiverlab.core.algebra import Algebra
    from quiverlab.fields.linalg import solve
    from quiverlab.modules import linalg_mod as lm
    dom = B0.domain
    r = B0.dim
    left = [B0.multiply(B0._basis_vec(a), e) for a in range(r)]        # B0 . e
    prods = [B0.multiply(l, B0._basis_vec(c)) for l in left for c in range(r)]   # B0.e.B0
    Jidx = lm.independent_modulo(prods, [], dom)
    Jbasis = [prods[i] for i in Jidx]
    std = [B0._basis_vec(i) for i in range(r)]
    comp_idx = lm.independent_modulo(std, Jbasis, dom)                 # complement of <e>
    comp = [std[i] for i in comp_idx]
    c = len(comp)
    basis_mat = lm.cols_to_matrix(comp + Jbasis)                       # square r x r, invertible

    def proj(x):
        sol = solve(basis_mat, list(x), dom)
        if sol is None:
            raise QuiverlabError(
                "tau_perpendicular_reduction: quotient projection failed -- the "
                "complement/ideal split is not a basis (bug)")
        return list(sol[:c])

    Tq = [[proj(B0.multiply(comp[i], comp[j])) for j in range(c)] for i in range(c)]
    unitq = proj(list(B0.unit))
    return Algebra.from_structure_constants(Tq, unitq, field=dom, check=True)


def _reduction_tau_rigid(A, Umod, eg):
    """``C(U) = End(T_U)/<e_U>`` for a tau-rigid indecomposable ``Umod`` (the DIJ idempotent
    quotient). ``T_U`` = an empty-support exchange-graph vertex (a genuine tau-tilting
    module) containing ``Umod``; ``e_U`` = its summand projector. Returns
    ``(C, pair, u_summand_indices)``."""
    from quiverlab.core.algebra import Algebra
    from quiverlab.core.basic import presented_form
    from quiverlab.fields.linalg import solve
    from quiverlab.modules.endomorphism import _structure_constants, _vec
    from quiverlab.modules.hom import is_isomorphic
    from quiverlab.modules.morphism import direct_sum

    def _iso(M):
        return (M.dim == Umod.dim
                and M.dimension_vector() == Umod.dimension_vector()
                and is_isomorphic(M, Umod))

    pair = None
    for rec in eg.vertices:
        if rec["support"]:                              # only genuine tau-tilting modules
            continue
        if any(_iso(M) for M in rec["pair"].summands):
            pair = rec["pair"]
            break
    if pair is None:
        raise QuiverlabError(
            "tau_perpendicular_reduction: no tau-tilting completion of U found among the "
            "empty-support exchange-graph vertices (U not tau-rigid, or tau-tilting-infinite)")
    summands = list(pair.summands)
    D, incls, projs = direct_sum(*summands)
    dom = D.domain
    Tsc, unit, _basis, Bmat = _structure_constants(D)
    B0 = Algebra.from_structure_constants(Tsc, list(unit), field=dom, check=True)
    r = B0.dim
    eU = [dom.zero()] * r
    uverts = []
    for i, Mi in enumerate(summands):
        if _iso(Mi):
            proj_endo = projs[i].then(incls[i])         # incl_i o proj_i : D -> D idempotent
            coords = solve(Bmat, _vec(proj_endo.matrix, D.dim), dom)
            if coords is None:
                raise QuiverlabError(
                    "tau_perpendicular_reduction: summand projector left the hom basis (bug)")
            eU = [dom.add(eU[t], coords[t]) for t in range(r)]
            uverts.append(i)
    C0 = _quotient_by_idempotent_sc(B0, eU)
    C = presented_form(C0)
    return C, pair, uverts


def tau_perpendicular_reduction(A, U, *, budget=512, _eg=None):
    """The Jasso tau-perpendicular reduction ``C(U)`` of a signed tau-exceptional object
    ``U`` (Plan 65 / R27), dispatching on the sign of ``U`` (H2):

    - ``U`` a **tau-rigid module** (a :class:`~quiverlab.modules.module.Module`, or a
      positive :class:`TauExcObject`): the DIJ quotient ``C(U) = End(T_U)/<e_U>`` (rank
      ``n - |U|``);
    - ``U`` a **shifted projective** ``P_v[1]`` (a negative :class:`TauExcObject`): the
      support quotient ``C(P_v[1]) = A/<e_v>`` (rank ``n - 1``), with the tautological
      restriction transport.

    Returns a :class:`TauReduction`. Self-certifies ``rk C(U) = n - |U|`` and (tau-rigid
    case) is discriminated by the ``C(S_1 of kA_3) = kA_2`` iso pin (H5)."""
    _require_quiver(A, "tau_perpendicular_reduction")
    if isinstance(U, TauExcObject) and U.sign < 0:      # shifted projective P_v[1]
        from quiverlab.modules.recollement import Recollement
        v = U.vertex
        recoll = Recollement(A, [v])
        return TauReduction(
            reduction_algebra=recoll.quotient, bongartz=None, u_vertices=[v],
            kind="shifted", equivalence=(lambda M, _r=recoll: _r.i_upper_star(M)))
    Umod = U.module if isinstance(U, TauExcObject) else U
    if Umod is None:
        raise QuiverlabError(
            "tau_perpendicular_reduction: a positive TauExcObject with no module")
    from quiverlab.tautilting.mutation import exchange_graph
    eg = _eg if _eg is not None else exchange_graph(A, budget_pairs=max(budget, 512))
    if eg.status != "complete":
        raise QuiverlabError(
            "tau_perpendicular_reduction: the exchange graph is not complete "
            f"(status={eg.status!r}); U cannot be tau-Bongartz-completed")
    C, pair, uverts = _reduction_tau_rigid(A, Umod, eg)
    return TauReduction(reduction_algebra=C, bongartz=pair, u_vertices=uverts,
                        kind="tau_rigid", equivalence=None)


